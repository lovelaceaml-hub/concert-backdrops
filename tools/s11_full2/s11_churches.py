def _birth_times(n):
    out = []
    for t, c in WAVES:
        out += [_snap(t)] * c
    while len(out) < n:                      # more buildings than waves: one per beat after the last wave
        out.append(_snap(out[-1] + 0.6))
    return out[:n]


