_KT = np.array([k["t"] for k in CAMERA_KEYS])
_CAM_NUM = ("pos", "target", "fov", "roll", "aperture")


def _tangents(name):
    """The speed of one camera quantity into and out of every key (see the tan modes above)."""
    q = [np.asarray(k[name], np.float64) for k in CAMERA_KEYS]
    n = len(q)
    vin, vout = [None] * n, [None] * n
    for i, k in enumerate(CAMERA_KEYS):
        back = (q[i] - q[i - 1]) / (_KT[i] - _KT[i - 1]) if i > 0 else None
        fwd = (q[i + 1] - q[i]) / (_KT[i + 1] - _KT[i]) if i < n - 1 else None
        if back is None or fwd is None:
            vin[i] = vout[i] = fwd if back is None else back
        elif k["tan"] == "hit":
            vin[i], vout[i] = back, fwd
        elif k["tan"] == "settle":
            vin[i] = vout[i] = fwd
        elif k["tan"] == "leave":
            vin[i] = vout[i] = back
        else:
            vin[i] = vout[i] = (q[i + 1] - q[i - 1]) / (_KT[i + 1] - _KT[i - 1])
    return vin, vout


_TAN = {name: _tangents(name) for name in _CAM_NUM}


def _log_between(p0, p1, e, anchor):
    """From p0 to p1 with the distance from the anchor changing by a constant factor (the pull back)."""
    v0, v1 = p0 - anchor, p1 - anchor
    d0, d1 = np.linalg.norm(v0), np.linalg.norm(v1)
    d = v0 / d0 * (1.0 - e) + v1 / d1 * e
    return anchor + d / np.linalg.norm(d) * d0 * (d1 / d0) ** e


def camera(t):
    """The camera at song time t: dict(pos, target, fov, roll, focus, aperture). A pure function of t.
    Phase B hands this to P3D["camera"] (or rebuilds it with CORE's orbit, dolly, crane and fly helpers)."""
    t = min(max(float(t), _KT[0]), _KT[-1])
    i = min(max(int(np.searchsorted(_KT, t, side="right")) - 1, 0), len(CAMERA_KEYS) - 2)
    a, b = CAMERA_KEYS[i], CAMERA_KEYS[i + 1]
    dt = b["t"] - a["t"]
    u = (t - a["t"]) / dt
    out = {}
    if a["move"] == "log":
        e = 1.0 - (1.0 - u) ** 2          # fastest on the downbeat, easing as the hands come into view
        lake = _v(*PLACES["lake"])
        out["pos"] = _log_between(a["pos"], b["pos"], e, lake)
        out["target"] = _log_between(a["target"], b["target"], e, lake)
        for name in ("fov", "roll", "aperture"):
            out[name] = float(a[name] * (1.0 - e) + b[name] * e)
    else:
        h00, h10 = 2 * u ** 3 - 3 * u ** 2 + 1, u ** 3 - 2 * u ** 2 + u
        h01, h11 = -2 * u ** 3 + 3 * u ** 2, u ** 3 - u ** 2
        for name in _CAM_NUM:
            vin, vout = _TAN[name]
            x = h00 * a[name] + h10 * dt * vout[i] + h01 * b[name] + h11 * dt * vin[i + 1]
            out[name] = x if name in ("pos", "target") else float(x)
    here = float(np.linalg.norm(out["target"] - out["pos"]))
    if a["focus"] is None and b["focus"] is None:
        out["focus"] = here                # the focus follows the target: the hands stay sharp
    else:
        fa = a["focus"] if a["focus"] is not None else float(np.linalg.norm(a["target"] - a["pos"]))
        fb = b["focus"] if b["focus"] is not None else float(np.linalg.norm(b["target"] - b["pos"]))
        s = u * u * (3 - 2 * u)
        out["focus"] = fa * (1 - s) + fb * s
    out["aperture"] = max(out["aperture"], 0.0)
    return out


def basis(cam):
    """(right, up, forward) of a camera dict, as p3d.api.CameraState.basis (roll left out)."""
    f = cam["target"] - cam["pos"]
    f = f / np.linalg.norm(f)
    r = np.cross(f, _v(0, 1, 0))
    r = r / np.linalg.norm(r)
    return r, np.cross(r, f), f


def project(cam, p):
    """Where a world point is in the frame: (x from the left, y from the bottom) in 0..1, and its depth."""
    r, u, f = basis(cam)
    d = np.asarray(p, np.float64) - cam["pos"]
    z = float(d @ f)
    fl = 1.0 / np.tan(np.radians(cam["fov"]) * 0.5)
    return 0.5 + 0.5 * float(d @ r) * fl / (ASPECT * z), 0.5 + 0.5 * float(d @ u) * fl / z, z


