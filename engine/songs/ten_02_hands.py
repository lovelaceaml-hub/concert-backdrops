# ----------------------------------------------------------------------------------------------------- camera
# One unbroken take. Each key: time, a place with the lens at azimuth az (degrees from +z toward +x), r metres
# from it and h metres above it, looking at the place plus `look`; or an absolute pos and target. fov is the
# vertical field of view in degrees, roll in degrees, ap the lens opening in metres (CameraState.aperture),
# focus in metres (default: the distance to the target, so the hands are sharp).
#   tan="hit"     the move changes at once (a contact, a snap)
#   tan="settle"  arrive already at the speed of the next, slower move (the start of a reading orbit)
#   tan="leave"   keep the speed of the move that ends here (the end of a reading orbit)
#   move="log"    from this key to the next the distance from the lake's middle grows by a constant factor
#                 per second (the pull back), not by constant metres
# Without tan the camera passes through the key without slowing (a spline), unlike a Track, which eases to
# a stop at each key.


def _v(*a):
    return np.array(a, dtype=np.float64)


def polar(az, dist, height=0.0):
    """The offset at azimuth az, dist metres out and height metres up (the convention of p3d.api.at)."""
    a = np.radians(az)
    return _v(np.sin(a) * dist, height, np.cos(a) * dist)


def K(t, place=None, az=0.0, r=1.0, h=0.0, look=(0.0, 0.0, 0.0), shift=(0.0, 0.0, 0.0), pos=None, target=None,
      fov=40.0, roll=0.0, ap=0.0, focus=None, tan="auto", move="spline", note=""):
    if pos is None:
        c = _v(*PLACES[place]) + _v(*shift)
        pos, target = c + polar(az, r, h), c + _v(*look)
    else:
        pos, target = _v(*pos), _v(*target)
    return dict(t=float(t), pos=pos, target=target, fov=float(fov), roll=float(roll), aperture=float(ap),
                focus=None if focus is None else float(focus), tan=tan, move=move, note=note)


