# ---------------------------------------------------------------------------------------------------- checks
def check():
    """The rules this timeline must keep; returns the lines of a report. Run: python engine/songs/ten_02_hands.py"""
    out = []
    assert all(b > a for a, b in zip(_KT[:-1], _KT[1:])), "camera key times must increase"
    assert _KT[0] == 0.0 and _KT[-1] == TOTAL
    assert sorted(w["n"] for w in WORDS) == list(range(1, 10)), "all nine expressions, once each"
    out.append("sections: " + ", ".join(f"{k} {n} {sec(k):g}" for k, n in enumerate(SECTION_NAMES, 1)))
    out.append("")
    out.append("the nine expressions (film order)")
    for w in WORDS:
        e = EXPRESSIONS[w["n"]]
        t0, t1 = w["read"]
        assert w["born"] <= t0 < t1 <= w["gone"] <= TOTAL
        assert t1 - t0 >= MIN_READ, f"{e['label']}: read {t1 - t0:.2f} s"
        pl = word_plane(w)
        chars = max(len(x) for x in e["lines"])
        assert w["width"] / chars >= MIN_CHAR, f"{e['label']}: letters too small ({w['width'] / chars:.4f})"
        seen = []
        for t in (t0, t1):
            cam = camera(t)
            x, y, z = project(cam, pl["centre"])
            half = pl["right"] * pl["width"] * 0.5
            xl, xr = project(cam, pl["centre"] - half)[0], project(cam, pl["centre"] + half)[0]
            to_cam = cam["pos"] - pl["centre"]
            ang = np.degrees(np.arccos(np.clip(to_cam @ pl["normal"] / np.linalg.norm(to_cam), -1, 1)))
            assert 0.05 <= min(xl, xr) and max(xl, xr) <= 0.95 and 0.5 < y < 0.92, \
                f"{e['label']} leaves the frame at {t:.2f}: x {xl:.2f} to {xr:.2f}, y {y:.2f}"
            assert ang <= MAX_OFF_SQUARE, f"{e['label']}: seen {ang:.0f} degrees off square"
            seen.append(f"x {xl:.2f} to {xr:.2f} y {y:.2f} off square {ang:.0f}")
        c = pl["centre"]
        out.append(f"  {w['n']} {e['label']:<13} read {t0:5.2f} to {t1:5.2f} ({t1 - t0:.1f} s)  at "
                   f"({c[0]:.2f}, {c[1]:.2f}, {c[2]:.2f}) m, {pl['width']:.2f} m wide, {pl['depth']:.2f} m "
                   f"from the lens")
        out.append(f"      start: {seen[0]};  end: {seen[1]}")
    for name, keys in list(WORLD.items()) + [("sun height", WORLD["sun"]["height"])]:
        if isinstance(keys, list):
            times = [k[0] for k in keys]
            assert all(y > x for x, y in zip(times[:-1], times[1:])), f"WORLD {name}: times must increase"
    for k in range(1, 9):
        end = S[k] if k < 8 else TOTAL
        assert any(sec(k) <= g["contact"] < end for g in GESTURES if g["section"] == k), f"section {k}: no touch"
    assert TOTAL - CARD_FULL >= 4.0, "the end card must be whole for at least 4 s"
    assert max(w["gone"] for w in WORDS) <= T_FORM, "no expression is still on screen when the title forms"
    out.append(f"  end card whole from {CARD_FULL:.2f} to {TOTAL:.2f} ({TOTAL - CARD_FULL:.1f} s)")
    out.append("")
    out.append("camera keys:  t   position (m)   target (m)   fov   focus (m)   opening (m)")
    for k in CAMERA_KEYS:
        c = camera(k["t"])
        p, g = c["pos"], c["target"]
        out.append(f"  {k['t']:6.2f}  ({p[0]:8.2f},{p[1]:7.2f},{p[2]:8.2f})  ({g[0]:7.2f},{g[1]:7.2f},{g[2]:7.2f})"
                   f"  {c['fov']:4.0f}  {c['focus']:8.2f}  {c['aperture']:.3f}  {k['tan']:<6} {k['note']}")
    for t in np.arange(0.0, TOTAL, 1.0 / FPS):
        c = camera(t)
        assert c["pos"][1] > 0.03, f"the camera is under the lake at {t:.2f}"
        assert 20.0 <= c["fov"] <= 60.0 and np.all(np.isfinite(c["pos"])) and c["focus"] > 0.1
    with open(os.path.abspath(__file__), encoding="utf-8") as f:
        src = f.read()
    assert not any(ch in src for ch in (chr(0x2013), chr(0x2014))), "no en dash or em dash anywhere"
    out.append("")
    out.append("ok")
    return out


