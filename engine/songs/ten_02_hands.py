def word_plane(w):
    """Where one expression stands in the world: centre, the directions of its plane, width in metres."""
    cam = camera(0.5 * (w["read"][0] + w["read"][1]))
    r, u, f = basis(cam)
    depth = w.get("depth") or cam["focus"]            # in the focal plane of the hands
    hh = depth * np.tan(np.radians(cam["fov"]) * 0.5)  # half the height of the frame at that depth
    fx, fy = w["frame"]
    centre = cam["pos"] + f * depth + r * ((fx - 0.5) * 2 * hh * ASPECT) + u * ((fy - 0.5) * 2 * hh)
    return dict(centre=centre, right=r, up=u, normal=-f, width=w["width"] * 2 * hh * ASPECT, depth=depth)


