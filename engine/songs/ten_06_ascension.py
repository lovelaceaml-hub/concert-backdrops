def _screen(t, pts):
    """Picture positions (x, y in 0..1, y up) and depths of world points for the camera at t (the same
    projection as p3d.api.CameraState.project, roll left out)."""
    pos, tgt, fov = cam_pos(t), cam_target(t), cam_fov(t)
    f = tgt - pos
    f = f / np.linalg.norm(f)
    r = np.cross(f, [0.0, 1.0, 0.0])
    r = r / np.linalg.norm(r)
    u = np.cross(r, f)
    d = np.asarray(pts, dtype=np.float64).reshape(-1, 3) - pos
    z = d @ f
    fl = 1.0 / np.tan(np.radians(fov) * 0.5)
    zs = np.where(np.abs(z) < 1e-9, 1e-9, z)
    return np.stack([(d @ r) * fl / (ASPECT * zs) * 0.5 + 0.5, (d @ u) * fl / zs * 0.5 + 0.5], axis=1), z


def word_block(w, t):
    """Centre, the four corners, the type height (metres) and the up direction of a phrase's block at t,
    turned and leaned to the camera by its billboard and tilt shares. Width from the longest line (0.43 em a
    letter), height from the lines and the label."""
    anchor = np.asarray(curve([(a, b) for a, b in w["anchor"]])(t), dtype=np.float64)
    scale = curve(w["scale"])(t) if "scale" in w else 1.0
    em = w["em"] * scale
    to_cam = cam_pos(t) - anchor
    az_cam = np.degrees(np.arctan2(to_cam[0], to_cam[2]))
    turn = (az_cam - w["facing"] + 180.0) % 360.0 - 180.0
    a = np.radians(w["facing"] + w["billboard"] * turn)
    right = np.array([np.cos(a), 0.0, -np.sin(a)])
    face = np.array([np.sin(a), 0.0, np.cos(a)])
    lean = w.get("tilt", 0.0) * np.arctan2(to_cam[1], np.hypot(to_cam[0], to_cam[2]))
    up = np.cos(lean) * np.array([0.0, 1.0, 0.0]) - np.sin(lean) * face
    half_w = 0.5 * 0.43 * em * max(len(line) for line in w["lines"])
    half_h = 0.5 * em * (1.25 * len(w["lines"]) + 0.9)
    corners = [anchor + sx * half_w * right + sy * half_h * up for sx in (-1, 1) for sy in (-1, 1)]
    return anchor, np.array(corners), em, up


def check(verbose=True):
    """Raises AssertionError when the plan breaks one of the film's own rules; prints a short table."""
    say = print if verbose else (lambda *a, **k: None)
    here = open(os.path.abspath(__file__), encoding="utf-8").read()
    assert chr(0x2013) not in here and chr(0x2014) not in here, "an en dash or em dash in this file"
    assert [e["label"] for e in EXPRESSIONS] == ["Greeting", "Gratitude", "Apology", "Inclusiveness", "Concession",
                                                 "Respect", "Encouragement", "Consideration", "Compliment"]
    assert sorted(w["label"] for w in WORDS3D) == sorted(e["label"] for e in EXPRESSIONS), "nine, once each"
    assert sorted(s["light"] for s in STARS) == list(range(9)), "each light of the arch gets one star"
    # the camera: one unbroken rise, always moving
    ts = np.arange(NFRAMES + 1) / FPS
    pos = np.array([cam_pos(t) for t in ts])
    dy = np.diff(pos[:, 1])
    assert dy.min() >= -1e-9, f"the camera descends at {ts[int(dy.argmin())]:.2f} s"
    step = np.linalg.norm(np.diff(pos, axis=0), axis=1) * FPS
    assert step.min() > 0.02, f"the camera stands still at {ts[int(step.argmin())]:.2f} s"
    say(f"camera: rises {pos[0, 1]:.2f} to {pos[-1, 1]:.1f} m, never descends; speed {step.min():.2f} to "
        f"{step.max():.1f} m/s")
    for k in range(len(ACTS)):
        t0, t1 = S[k], (S[k + 1] if k + 1 < len(S) else TOTAL)
        say(f"  act {k} {ACTS[k]:8s} {t0:5.1f} to {t1:5.1f} s   camera {cam_pos(t0)[1]:6.1f} to "
            f"{cam_pos(t1)[1]:6.1f} m")
    # the words: a clear reading of 2.5 s or more, inside the picture, large enough for a phone
    for w in WORDS3D:
        r0, r1 = w["read"]
        assert r1 - r0 >= 2.5 - 1e-9, f"{w['label']}: reading time {r1 - r0:.2f} s"
        lo_em, hi_w, worst = 9.0, 0.0, 0.0
        for t in np.linspace(r0, r1, 13):
            anchor, corners, em, up = word_block(w, t)
            xy, z = _screen(t, corners)
            assert z.min() > 0.2, f"{w['label']} at {t:.2f} s: behind or in the camera"
            worst = max(worst, float(np.abs(xy - 0.5).max()))
            e0, e1 = _screen(t, [anchor - up * em / 2, anchor + up * em / 2])[0]
            lo_em = min(lo_em, float(np.linalg.norm(e1 - e0)))
            hi_w = max(hi_w, float(xy[:, 0].max() - xy[:, 0].min()))
        assert worst <= 0.5, f"{w['label']}: leaves the picture during its reading (edge at {worst:.2f})"
        assert lo_em >= 1.0 / 12.0, f"{w['label']}: type only {lo_em:.3f} of the picture height"
        say(f"  {w['label']:14s} read {r0:5.2f} to {r1:5.2f} ({r1 - r0:.1f} s)  type {lo_em * H:4.0f} px at 1080p, "
            f"block up to {hi_w * 100:3.0f}% of the width, light {w['star'][0] + 1} at {w['star'][1]:.1f} s")
    # the people: large in the frame in the close shots
    for t, feet, height, least in CLOSE_SHOTS:
        feet = np.asarray(feet, dtype=np.float64)
        xy, z = _screen(t, [feet, feet + [0.0, height, 0.0]])
        share = abs(xy[1, 1] - xy[0, 1])
        assert z.min() > 0.3 and share >= least, f"close shot at {t:.2f} s: the person is {share:.2f} of the height"
    say(f"  {len(CLOSE_SHOTS)} close shots hold their person at 0.30 of the picture height or more")
    # the people: never seen from the front (0 degrees is a front view, 90 a side profile, 180 from behind)
    least = 180.0
    for b in BLOCKING:
        if "path" not in b:
            continue
        keys, height = b["path"], CAST[b["who"]]["height"]
        kt = [k[0] for k in keys]
        for t in np.arange(max(b["t0"], 0.0), min(b["t1"], TOTAL), 0.1):
            j = max(0, int(np.searchsorted(kt, t, side="right")) - 1)
            at = np.asarray(keys[j][1], dtype=np.float64)
            if j + 1 < len(keys) and t >= kt[0]:
                at = at + (np.asarray(keys[j + 1][1]) - at) * (t - kt[j]) / (kt[j + 1] - kt[j])
            xy, z = _screen(t, [at + [0.0, 0.75 * height, 0.0]])
            to_cam = cam_pos(t) - at
            if z[0] < 0.3 or np.abs(xy - 0.5).max() > 0.5 or np.hypot(to_cam[0], to_cam[2]) < 0.7 * abs(to_cam[1]):
                continue          # out of the picture, or seen from straight above or below
            angle = abs((np.degrees(np.arctan2(to_cam[0], to_cam[2])) - keys[j][2] + 180.0) % 360.0 - 180.0)
            assert angle >= 55.0, f"{b['who']} is seen from the front at {t:.1f} s ({angle:.0f} degrees)"
            least = min(least, angle)
    say(f"  nobody is seen from the front: the least angle between a body's facing and the camera is {least:.0f} "
        f"degrees (90 is a side profile)")
    # the end card
    assert TOTAL - TAG_T1 >= 4.0, "the end card must be readable for at least 4 s"
    assert abs(TITLE_HIT - (T_FORM + FORM_DUR + 0.75)) < 1e-9
    assert FADE(0.0) == 1.0 and FADE(TOTAL) == 1.0, "never black"
    say(f"  end card: title whole at {TITLE_HIT:.1f} s, lines readable {TAG_T1:.1f} to {TOTAL:.1f} s "
        f"({TOTAL - TAG_T1:.1f} s)")
    return True


