class _RingSet:
    """Blocking only: the rings people stand on, as circles of points (replaced by the real look in phase B)."""

    def __init__(self):
        rng = np.random.default_rng(606)
        self.parts = []
        for r in RINGS:
            n = 2600
            a = rng.random(n) * 2 * np.pi
            if r.get("hoop"):
                rad = r["radius"] * (1.0 + 0.03 * rng.normal(size=n))
            else:
                rad = r["radius"] * np.round(rng.random(n) * 5 + 0.5) / 5.5 + 0.01 * rng.normal(size=n)
            pos = np.stack([np.cos(a) * rad, np.full(n, r["y"]), np.sin(a) * rad], axis=1)
            self.parts.append((r, pos.astype(np.float32)))

    def sample(self, t):
        out = []
        for r, pos in self.parts:
            g = min(max((t - r["t0"]) / 0.8, 0.0), 1.0) * min(max((r["t1"] - t) / 1.2, 0.0), 1.0)
            if g > 0.0:
                out.append(dict(pos=pos, size=0.02, color=lin(r["color"]), alpha=0.5 * g, kind="soft", twinkle=0.5))
        return out


def build(scene):
    """Fills the 3D scene. PHASE A: a blocking pass only (rings, and stand-in people where BLOCKING puts them),
    enough for the first camera stills once CORE's renderer runs. PHASE B replaces this with BODY's people,
    WORDS' words, the shafts, the pillars, the cloud, the fountains and the arch, from the data above."""
    scene.add("rings", _RingSet(), reflect=True)
    if p3d is None or not hasattr(p3d, "StandIn"):
        return
    for i, b in enumerate(BLOCKING):
        if "path" not in b:
            continue
        who = CAST[b["who"]]
        t_mid = 0.5 * (max(b["t0"], 0.0) + b["t1"])
        keys = b["path"]
        k = min(range(len(keys)), key=lambda j: abs(keys[j][0] - t_mid))
        body = p3d.StandIn(pos=keys[k][1], height=who["height"], color=who["colors"][1], facing=keys[k][2],
                           look="rim" if b["fill"][0][1] < 0.2 else "glitter", seed=600 + i)
        t0, t1 = b["t0"], b["t1"]
        body.gain = (lambda t, t0=t0, t1=t1: 1.0 if t0 <= t <= t1 else 0.0)
        scene.add(f"{b['who']} {i}", body)


