def lin(hexs):
    """A display hex colour as linear light (the same curve as p3d.api.lin and the other song files)."""
    h = hexs.lstrip("#")
    return np.array([int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)], dtype=np.float64) ** 2.2


def P(az, dist, height=0.0):
    """The point at azimuth az (degrees from +z toward +x), dist metres from the shaft, height metres up.
    The same convention as p3d.api.at."""
    a = np.radians(az)
    return (float(np.sin(a) * dist), float(height), float(np.cos(a) * dist))


def curve(keys):
    """A smooth function of t through (t, value) keys that never overshoots a key (a monotone cubic, Fritsch
    and Carlson): a height that rises from key to key rises at every instant between them."""
    ts = np.array([k[0] for k in keys], dtype=np.float64)
    vs = np.array([np.atleast_1d(np.asarray(k[1], dtype=np.float64)) for k in keys])
    if np.any(np.diff(ts) <= 0):
        raise ValueError(f"curve: key times must be strictly increasing, got {list(ts)}")
    h = np.diff(ts)
    d = np.diff(vs, axis=0) / h[:, None]
    m = np.zeros_like(vs)
    m[0], m[-1] = d[0], d[-1]          # already under way at the first key, still going at the last
    if len(ts) > 2:
        w1 = (2 * h[1:] + h[:-1])[:, None]
        w2 = (h[1:] + 2 * h[:-1])[:, None]
        same = d[:-1] * d[1:] > 0
        den = w1 / np.where(same, d[:-1], 1.0) + w2 / np.where(same, d[1:], 1.0)
        m[1:-1] = np.where(same, (w1 + w2) / den, 0.0)

    def f(t):
        t = min(max(float(t), ts[0]), ts[-1])
        i = min(int(np.searchsorted(ts, t, side="right")) - 1, len(ts) - 2)
        u = (t - ts[i]) / h[i]
        h00, h10 = (1 + 2 * u) * (1 - u) ** 2, u * (1 - u) ** 2
        h01, h11 = u * u * (3 - 2 * u), u * u * (u - 1)
        v = h00 * vs[i] + h10 * h[i] * m[i] + h01 * vs[i + 1] + h11 * h[i] * m[i + 1]
        return float(v[0]) if v.shape[0] == 1 else v
    return f


