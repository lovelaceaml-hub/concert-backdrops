# ------------------------------------------------------------------------------------- the camera as a function
def _key_at(t):
    ks = CAMERA
    if t <= ks[0]["t"]:
        return 0, 0.0
    for i in range(len(ks) - 1):
        if ks[i]["t"] <= t <= ks[i + 1]["t"]:
            return i, (t - ks[i]["t"]) / (ks[i + 1]["t"] - ks[i]["t"])
    return len(ks) - 2, 1.0


def _spline(name, i, u):
    """Catmull-Rom through the keys with time-aware tangents: a stand-in for CORE's fly(path)."""
    ks = CAMERA
    p0, p1 = ks[i][name], ks[i + 1][name]
    a, b = ks[max(i - 1, 0)], ks[min(i + 2, len(ks) - 1)]
    dt = ks[i + 1]["t"] - ks[i]["t"]
    out = []
    for c in range(3):
        m0 = (p1[c] - a[name][c]) / max(ks[i + 1]["t"] - a["t"], 1e-6) * dt
        m1 = (b[name][c] - p0[c]) / max(b["t"] - ks[i]["t"], 1e-6) * dt
        h00, h10 = 2 * u ** 3 - 3 * u ** 2 + 1, u ** 3 - 2 * u ** 2 + u
        h01, h11 = -2 * u ** 3 + 3 * u ** 2, u ** 3 - u ** 2
        out.append(h00 * p0[c] + h10 * m0 + h01 * p1[c] + h11 * m1)
    return tuple(out)


def camera_at(t):
    """The camera at time t: dict(pos, target, fov, roll, focus, aperture). A pure function of t."""
    i, u = _key_at(t)
    s = u * u * (3 - 2 * u)
    a, b = CAMERA[i], CAMERA[i + 1]
    return dict(pos=_spline("pos", i, u), target=_spline("target", i, u),
                fov=a["fov"] + (b["fov"] - a["fov"]) * s, roll=a["roll"] + (b["roll"] - a["roll"]) * s,
                focus=a["focus"] + (b["focus"] - a["focus"]) * s, aperture=a["ap"] + (b["ap"] - a["ap"]) * s)


