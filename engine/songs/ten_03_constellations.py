# ---------------------------------------------------------------------------------------- checks (numpy only)
def _project(cam, pts):
    f = cam["target"] - cam["pos"]
    f = f / np.linalg.norm(f)
    r = np.cross(f, [0.0, 1.0, 0.0])
    r = r / np.linalg.norm(r)
    u = np.cross(r, f)
    d = np.asarray(pts, float).reshape(-1, 3) - cam["pos"]
    z = d @ f
    fl = 1.0 / np.tan(np.radians(cam["fov"]) * 0.5)
    return np.stack([(d @ r) * fl / (ASPECT * z) * 0.5 + 0.5, (d @ u) * fl / z * 0.5 + 0.5], axis=1), z


def word_frame(e, t):
    """World centre, right vector, normal and block height of an expression at t (a ring follows the camera)."""
    st = STAGES[e["stage"]]
    n_lines = len(e["lines"])
    height = n_lines * 1.75 * e["cap"] + 1.6 * e["label_cap"]
    if "ring" in e:
        c = st.w(e["ring"]["center"])
        to_cam = camera(t)["pos"] - c
        to_cam[1] = 0.0
        n = to_cam / np.linalg.norm(to_cam)
        return c + n * e["ring"]["radius"], np.array([n[2], 0.0, -n[0]]), n, height
    a = np.radians(st.az + e["yaw"])
    n = np.array([np.sin(a), 0.0, np.cos(a)])
    return st.w(e["center"]), np.array([np.cos(a), 0.0, -np.sin(a)]), n, height


def check(verbose=True):
    """Checks the plan: reading times, the framing of every expression, the camera path. Returns problems."""
    bad = []
    for e in EXPRESSIONS:
        t0, t1 = e["read"]
        if t1 - t0 < MIN_READ - 1e-6:
            bad.append(f"{e['key']}: read for {t1 - t0:.2f} s")
        if not (e["arrive"]["t1"] <= t0 + 1e-6 and e["leave"]["t0"] >= t1 - 0.25):
            bad.append(f"{e['key']}: arrive, read and leave overlap")
        for t in np.linspace(t0, t1, 5):
            cam = camera(t)
            c, right, n, height = word_frame(e, t)
            to_cam = cam["pos"] - c
            dist = float(np.linalg.norm(to_cam))
            skew = float(np.degrees(np.arccos(np.clip(to_cam @ n / dist, -1, 1))))
            up = np.array([0.0, 1.0, 0.0])
            corners = [c + sx * right * e["width"] / 2 + sy * up * height / 2 for sx in (-1, 1) for sy in (-1, 1)]
            xy, z = _project(cam, corners)
            frac = float(xy[:, 0].max() - xy[:, 0].min())
            frame_h = 2.0 * dist * np.tan(np.radians(cam["fov"]) * 0.5)
            cap_px, label_px = e["cap"] / frame_h * H, e["label_cap"] / frame_h * H
            row = (f"  {e['key']:14s} t {t:5.2f}  dist {dist:5.1f} m  skew {skew:4.1f} deg  width {frac * 100:3.0f}% "
                   f"x {xy[:, 0].min():.2f}..{xy[:, 0].max():.2f} y {xy[:, 1].min():.2f}..{xy[:, 1].max():.2f}  "
                   f"capital {cap_px:3.0f} px  label {label_px:3.0f} px")
            if verbose:
                print(row)
            if skew > 16.0 or not 0.42 <= frac <= 0.86 or cap_px < 50 or label_px < 32 or z.min() <= 0:
                bad.append("framing:" + row)
            if xy[:, 0].min() < 0.04 or xy[:, 0].max() > 0.96 or xy[:, 1].min() < 0.30 or xy[:, 1].max() > 0.97:
                bad.append("out of the safe area:" + row)
    ts = np.arange(0.0, TOTAL + 1e-9, 1.0 / FPS)
    pos = np.array([camera(t)["pos"] for t in ts])
    if pos[:, 1].min() < 0.25:
        bad.append(f"camera under 0.25 m at {ts[pos[:, 1].argmin()]:.2f} s ({pos[:, 1].min():.2f} m)")
    speed = np.linalg.norm(np.diff(pos, axis=0), axis=1) * FPS
    if verbose:
        for i in range(len(SECTIONS)):
            m = (ts[:-1] >= S(i)) & (ts[:-1] < (SECTIONS[i + 1] if i + 1 < len(SECTIONS) else TOTAL))
            print(f"  S{i} {SECTION_NAMES[i]:24s} camera speed {speed[m].min():6.1f} to {speed[m].max():6.1f} m/s")
    if speed.min() < 0.02:
        bad.append(f"camera stands still at {ts[speed.argmin()]:.2f} s")
    if any(b["t"] <= a["t"] for a, b in zip(CAMERA_KEYS, CAMERA_KEYS[1:])):
        bad.append("camera keys out of order")
    lights = sorted(e["light"] for e in EXPRESSIONS)
    if lights != list(range(9)) or max(e["light_at"] for e in EXPRESSIONS) > ARCH_DRAWN:
        bad.append("the nine lights are not all lit before the arch is drawn")
    if TOTAL - CARD_READABLE < 4.0:
        bad.append("end card readable for less than 4 s")
    return bad


