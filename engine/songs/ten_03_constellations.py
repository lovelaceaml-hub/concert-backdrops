def at(az, dist, height=0.0):
    """As p3d.api.at: the point at azimuth az (degrees from +z toward +x), dist from the y axis, height up."""
    a = np.radians(az)
    return np.array([np.sin(a) * dist, height, np.cos(a) * dist])


# The arch: a half circle of radius R over the origin in the plane z = 0. Light i (0 Greeting to 8 Compliment)
