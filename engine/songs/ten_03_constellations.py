def _tangents(ts, vs, reads, eases):
    """Catmull-Rom tangents on uneven times; still at both ends. The two keys of a reading moment take the
    slope of the straight line between them: the camera eases into the moment and drifts steadily through it.
    A key marked ease=True (a close-up) is arrived at softly: it is passed at no more than 1.2 m a second,
    already heading for the next key."""
    n = len(ts)
    out = np.zeros_like(vs)
    for j in range(n):
        if reads[j] and j + 1 < n and reads[j + 1] == reads[j]:
            out[j] = (vs[j + 1] - vs[j]) / (ts[j + 1] - ts[j])
        elif reads[j] and j > 0 and reads[j - 1] == reads[j]:
            out[j] = (vs[j] - vs[j - 1]) / (ts[j] - ts[j - 1])
        elif eases[j] and j + 1 < n:
            slope = (vs[j + 1] - vs[j]) / (ts[j + 1] - ts[j])
            out[j] = slope * min(1.0, 1.2 / max(np.linalg.norm(slope[:3]), 1e-9))
        elif 0 < j < n - 1:
            out[j] = (vs[j + 1] - vs[j - 1]) / (ts[j + 1] - ts[j - 1])
    return out


def _hermite(ts, vs, tans, t):
    if t <= ts[0]:
        return vs[0]
    if t >= ts[-1]:
        return vs[-1]
    i = int(np.searchsorted(ts, t, side="right")) - 1
    h = ts[i + 1] - ts[i]
    u = (t - ts[i]) / h
    u2, u3 = u * u, u * u * u
    h00, h10, h01, h11 = 2 * u3 - 3 * u2 + 1, u3 - 2 * u2 + u, -2 * u3 + 3 * u2, u3 - u2
    return h00 * vs[i] + h10 * h * tans[i] + h01 * vs[i + 1] + h11 * h * tans[i + 1]


_KT = np.array([k["t"] for k in CAMERA_KEYS], float)
# one row per key: position (3), target (3), field of view, roll
_KV = np.array([np.concatenate([*_key_world(k), [k["fov"], k["roll"]]]) for k in CAMERA_KEYS], float)
_KTAN = _tangents(_KT, _KV, [k.get("read") for k in CAMERA_KEYS], [k.get("ease", False) for k in CAMERA_KEYS])
_KAP = [k["aperture"] for k in CAMERA_KEYS]


def camera(t):
    """The camera at t, as the fields of p3d.api.CameraState (phase B hands these to engine-p3d's camera, or
    rebuilds the path from its orbit, dolly, crane and fly helpers using the same keys)."""
    v = _hermite(_KT, _KV, _KTAN, t)
    pos, look = v[0:3], v[3:6]
    return dict(pos=pos, target=look, fov=float(v[6]), roll=float(v[7]), focus=float(np.linalg.norm(look - pos)),
                aperture=float(np.interp(t, _KT, _KAP)), aspect=ASPECT)


