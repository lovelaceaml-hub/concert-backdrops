class Stage:
    """A place in the film with its own axes: x to the right as the reading camera sees it, y up, z toward
    the reading camera. `az` is the azimuth of that z axis. Local metres to world metres with w()."""

    def __init__(self, origin, az):
        self.origin = np.asarray(origin, float)
        a = np.radians(az)
        self.az = float(az)
        self.fwd = np.array([np.sin(a), 0.0, np.cos(a)])
        self.right = np.array([np.cos(a), 0.0, -np.sin(a)])

    def w(self, p):
        p = np.asarray(p, float)
        return self.origin + p[0] * self.right + p[1] * np.array([0.0, 1.0, 0.0]) + p[2] * self.fwd

    def orbit(self, az, radius, height, center=(0.0, 0.0, 0.0)):
        """World point on a circle round `center` (local), at local azimuth az (0 = on the local z axis)."""
        a = np.radians(az)
        c = np.asarray(center, float)
        return self.w((c[0] + np.sin(a) * radius, c[1] + height, c[2] + np.cos(a) * radius))


