def _hermite(ts, vs, t):
    """A smooth curve through the keys that never overshoots them (monotone cubic, uneven times): the camera
    does not stop at a key, and it does not swing wide before a sharp turn."""
    ts = np.asarray(ts, np.float64)
    vs = np.asarray(vs, np.float64).reshape(len(ts), -1)
    t = min(max(t, ts[0]), ts[-1])
    i = int(min(max(np.searchsorted(ts, t, side="right") - 1, 0), len(ts) - 2))
    h = np.diff(ts)[:, None]
    d = np.diff(vs, axis=0) / h
    m = np.zeros_like(vs)
    m[0], m[-1] = d[0], d[-1]
    w1, w2 = 2.0 * h[1:] + h[:-1], h[1:] + 2.0 * h[:-1]
    same = d[:-1] * d[1:] > 0.0
    with np.errstate(divide="ignore", invalid="ignore"):
        m[1:-1] = np.where(same, (w1 + w2) / (w1 / d[:-1] + w2 / d[1:]), 0.0)
    dt = ts[i + 1] - ts[i]
    x = (t - ts[i]) / dt
    h00, h10 = 2 * x ** 3 - 3 * x ** 2 + 1, x ** 3 - 2 * x ** 2 + x
    h01, h11 = -2 * x ** 3 + 3 * x ** 2, x ** 3 - x ** 2
    return h00 * vs[i] + h10 * dt * m[i] + h01 * vs[i + 1] + h11 * dt * m[i + 1]


