_GRID = np.arange(0.0, TOTAL + 1e-9, 1.0 / 240.0)


def _integral(rate):
    v = np.array([rate(float(t)) for t in _GRID])
    return np.concatenate([[0.0], np.cumsum(0.5 * (v[1:] + v[:-1]) * np.diff(_GRID))])


_R = _integral(WAVE_SPEED)
_C = _integral(lambda t: WAVE_SPEED(t) if t <= BREAK else CARRIER_SPEED(t))
_CLOCK = _integral(TIME_RATE)


def wave_r(t):
    """Metres from the drop point to the crest at t."""
    return float(np.interp(t, _GRID, _R))


def carrier_r(t):
    """Metres from the drop point to the camera's frame at t (the same as wave_r until the break)."""
    return float(np.interp(t, _GRID, _C))


def wave_clock(t):
    """The wave's own time at t (slow motion is a slower clock)."""
    return float(np.interp(t, _GRID, _CLOCK))


