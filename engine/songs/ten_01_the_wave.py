def spark_y(t):
    """Height of the falling spark (it is already falling on the first frame)."""
    return SPARK_FROM * (1.0 - min(max(t / IMPACT, 0.0), 1.0) ** 1.3)


def _front_z(r, u):
    return Z0 - float(np.sqrt(max(r * r - u * u, 0.0)))


def to_world(p, t, carrier=False):
    """A wave frame point (u, b, h) at time t, in world metres. carrier=True: the camera's frame."""
    u, b, h = p
    return np.array([X_DROP + u, h, _front_z(carrier_r(t) if carrier else wave_r(t), u) + b])


def behind(T, t, u=0.0):
    """How many metres behind the crest (b) something is at t that the crest reached at time T."""
    return _front_z(wave_r(T), u) - _front_z(wave_r(t), u)


def ahead_r(r, t, u=0.0):
    """b at time t of something that stands r metres from the drop point (negative while it is still ahead)."""
    return _front_z(r, u) - _front_z(wave_r(t), u)


def stand(T, u):
    """World point on the water that the crest reaches at time T, u metres along it."""
    return np.array([X_DROP + u, 0.0, _front_z(wave_r(T), u)])


