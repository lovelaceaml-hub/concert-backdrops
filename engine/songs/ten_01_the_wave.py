    for s in SECTIONS:
        for t in (sec(s["n"]), sec(s["n"], 3.75)):
            c, c2 = camera_state(t), camera_state(t + 0.05)
            v = np.linalg.norm(c2["pos"] - c["pos"]) / 0.05
            print(f"{t:5.1f}  {wave_r(t):9.1f} m {WAVE_SPEED(t):5.1f} m/s {WAVE_HEIGHT(t):5.1f} m      "
                  f"{c['pos'][0]:7.1f} {c['pos'][1]:6.2f} {c['pos'][2]:7.1f}  {c['fov']:4.0f}  {v:5.1f} m/s"
                  + (f"   S{s['n']} {s['name']}" if t == sec(s["n"]) else ""))
    lowest = min(camera_state(float(t))["pos"][1] for t in np.arange(0.0, TOTAL, 1.0 / FPS))
    print(f"\nlowest camera height {lowest:.2f} m")
    still = [float(t) for t in np.arange(0.0, TOTAL - 0.2, 0.1)
             if np.linalg.norm(camera_state(float(t) + 0.1)["pos"] - camera_state(float(t))["pos"]) < 0.004]
    if still:
        problems.append(f"the camera stands still near {still[:6]}")
    zs = np.array([camera_state(float(t))["pos"][2] for t in np.arange(0.0, TOTAL, 0.1)])
    back = float(np.max(np.maximum.accumulate(-zs) + zs))      # the furthest the camera ever goes back up the lake
    print(f"furthest the camera ever travels back up the lake {back:.2f} m")
    if back > 0.5:
        problems.append(f"the camera travels backward by {back:.1f} m")
    print("\nthe nine expressions: read from, to, seconds; capital height and widest line as a share of the "
          "picture at the start, middle and end; seen at (cosine); centre x, y")
    for e in EXPRESSIONS:
        t0, t1 = e["read"]
        rows = [reading(e, t) for t in (t0, 0.5 * (t0 + t1), t1 - 0.05)]
        flags = []
        if t1 - t0 < MIN_READ - 1e-6:
            flags.append("short")
        if min(r[0] for r in rows) < MIN_CAP:
            flags.append("small")
        if max(r[1] for r in rows) > MAX_WIDTH:
            flags.append("wide")
        if min(r[2] for r in rows) < 0.8:
            flags.append("oblique")
        if any(not (0.12 < r[3] < 0.88 and 0.15 < r[4] < 0.9) for r in rows):
            flags.append("off centre")
        print(f"  {e['n']} {e['label']:<14} {t0:5.1f} {t1:5.1f} {t1 - t0:4.1f} s   cap "
              + " ".join(f"{100 * r[0]:4.1f}%" for r in rows) + "   width "
              + " ".join(f"{100 * r[1]:3.0f}%" for r in rows) + f"   cos {min(r[2] for r in rows):.2f}   at "
              + " ".join(f"({r[3]:.2f},{r[4]:.2f})" for r in rows) + ("   <-- " + ", ".join(flags) if flags else ""))
        if flags:
            problems.append(f"{e['label']}: {', '.join(flags)}")
    card = TOTAL - CARD_WHOLE
    print(f"\nend card whole from {CARD_WHOLE:.1f} s: {card:.1f} s (at least 4)")
    if card < 4.0:
        problems.append("end card under 4 s")
    print("\n" + ("PROBLEMS: " + "; ".join(problems) if problems else "ok"))
    return problems


