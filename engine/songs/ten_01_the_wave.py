def camera_state(t):
    """The camera at t, in world metres: dict(pos, target, fov, roll, focus, aperture). A pure function of t.
    (Phase B hands this to P3D["camera"], or rebuilds it from CORE's fly() and orbit() helpers.)"""
    carrier = t >= BREAK
    pos = to_world(_hermite(_KT, [k[1] for k in CAMERA_KEYS], t), t, carrier)
    target = to_world(_hermite(_KT, [k[2] for k in CAMERA_KEYS], t), t, carrier)
    fov, roll, aperture = (float(_hermite(_KT, [k[j] for k in CAMERA_KEYS], t)[0]) for j in (3, 4, 5))
    pos[1] = max(pos[1], 0.12)       # never under the water
    return dict(pos=pos, target=target, fov=fov, roll=roll, focus=float(np.linalg.norm(target - pos)),
                aperture=max(aperture, 0.0))


