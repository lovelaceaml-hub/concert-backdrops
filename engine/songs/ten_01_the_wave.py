_FACES = {"+b": (0.0, 0.0, 1.0), "-b": (0.0, 0.0, -1.0), "+u": (1.0, 0.0, 0.0)}


def reading(e, t):
    """How expression e sits in the picture at t: (capital height and widest line as shares of the picture,
    cosine of the angle it is seen at, x and y of its centre in 0..1 with y up)."""
    cam = camera_state(t)
    centre = to_world(e["where"](t), t)
    f = cam["target"] - cam["pos"]
    f /= np.linalg.norm(f)
    r = np.cross(f, [0.0, 1.0, 0.0])
    r /= np.linalg.norm(r)
    up = np.cross(r, f)
    d = centre - cam["pos"]
    depth = float(d @ f)
    half = depth * np.tan(np.radians(cam["fov"]) * 0.5)
    widest = max(len(line) for line in e["lines"]) * 0.735 * e["cap"]
    cos = 1.0 if e["faces"] == "camera" else float(-np.dot(_FACES[e["faces"]], d / np.linalg.norm(d)))
    return (e["cap"] / (2.0 * half), widest * cos / (2.0 * half * ASPECT), cos,
            0.5 + 0.5 * float(d @ r) / (half * ASPECT), 0.5 + 0.5 * float(d @ up) / half)


