_FIELDS = ("pos", "target", "fov", "roll", "focus", "aperture", "up")
_CURVES = {}


def _curve(name):
    """Key times, values and slopes of one camera field. The slopes are those of a monotone cubic (no
    overshoot): a value that is held between two keys stays held, and the path has no corners."""
    if name not in _CURVES:
        t = np.array([k["t"] for k in CAMERA])
        y = np.array([np.atleast_1d(np.asarray(k[name], np.float64)) for k in CAMERA])
        h = np.diff(t)[:, None]
        d = np.diff(y, axis=0) / h
        m = np.zeros_like(y)
        m[0], m[-1] = d[0], d[-1]
        w1, w2 = 2.0 * h[1:] + h[:-1], h[1:] + 2.0 * h[:-1]
        same = d[:-1] * d[1:] > 0.0
        with np.errstate(divide="ignore", invalid="ignore"):
            inner = (w1 + w2) / (w1 / d[:-1] + w2 / d[1:])
        m[1:-1] = np.where(same, inner, 0.0)
        _CURVES[name] = (t, y, m)
    return _CURVES[name]


def _value(name, t):
    ts, y, m = _curve(name)
    if t <= ts[0]:
        return y[0]
    if t >= ts[-1]:
        return y[-1]
    i = int(np.searchsorted(ts, t, side="right")) - 1
    h = ts[i + 1] - ts[i]
    u = (t - ts[i]) / h
    return ((2 * u ** 3 - 3 * u ** 2 + 1) * y[i] + (u ** 3 - 2 * u ** 2 + u) * h * m[i]
            + (-2 * u ** 3 + 3 * u ** 2) * y[i + 1] + (u ** 3 - u ** 2) * h * m[i + 1])


def camera(t):
    """The camera at song time t: a pure function of t (any frame can be rendered on its own).
    Returns pos, target and up (metres, vectors), fov and roll (degrees), focus (metres), aperture (metres)."""
    out = {name: _value(name, float(t)) for name in _FIELDS}
    for name in ("fov", "roll", "focus", "aperture"):
        out[name] = float(out[name][0])
    out["up"] = unit(out["up"])
    out["aperture"] = max(out["aperture"], 0.0)
    return out


