def v(x, y, z):
    return np.array([x, y, z], dtype=np.float64)


def ground(x, z):
    return v(x, 0.0, z)


def unit(a):
    a = np.asarray(a, dtype=np.float64)
    return a / max(np.linalg.norm(a), 1e-12)


def right_of(d):
    """The unit vector to the right of a level heading d (y up)."""
    return unit(v(-d[2], 0.0, d[0]))


def local(center, az, radius, height=0.0):
    """The point at azimuth az (degrees from +z toward +x, as engine/p3d/api.at) round a centre."""
    a = np.radians(az)
    return np.asarray(center, dtype=np.float64) + v(np.sin(a) * radius, height, np.cos(a) * radius)


def heading_az(d):
    return float(np.degrees(np.arctan2(d[0], d[2])))


