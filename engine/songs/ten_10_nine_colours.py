def lin(hexs):
    """A display hex colour as linear light (the same curve as engine/p3d/api.py)."""
    h = hexs.lstrip("#")
    return np.array([int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)], dtype=np.float64) ** 2.2


def stage(hexs, k=None):
    """The ribbon trail colour of a campaign colour: the same hue, deepened by STAGE_DEEPEN (linear light)."""
    c = lin(hexs)
    m = c.max()
    return m * (c / m) ** (STAGE_DEEPEN if k is None else k)


