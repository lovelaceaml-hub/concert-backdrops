def _project(c, point):
    """Where a world point falls in the picture of camera state c: ((x, y) in 0..1, y up), depth in metres."""
    f = unit(c["target"] - c["pos"])
    r = unit(np.cross(f, c["up"]))
    u = np.cross(r, f)
    d = np.asarray(point, np.float64) - c["pos"]
    z = float(d @ f)
    k = 1.0 / np.tan(np.radians(c["fov"]) * 0.5)
    return (0.5 + 0.5 * float(d @ r) * k / (ASPECT * z), 0.5 + 0.5 * float(d @ u) * k / z), z


def _check():
    problems = []
    ts = [k["t"] for k in CAMERA]
    if any(b <= a for a, b in zip(ts, ts[1:])):
        problems.append("camera key times are not strictly increasing")
    if ts[0] != 0.0 or ts[-1] != TOTAL:
        problems.append("the camera does not cover 0 to %g" % TOTAL)
    for i in range(int(TOTAL * 10) + 1):
        c = camera(i / 10.0)
        if c["pos"][1] < 0.3:
            problems.append("camera under 0.3 m above the lake at %.1f s (%.2f m)" % (i / 10.0, c["pos"][1]))
            break
    if sorted(w["n"] for w in WORDS) != list(range(1, 10)):
        problems.append("the nine expressions are not each shown exactly once")
    if [w["n"] for w in WORDS] != ORDER:
        problems.append("WORDS is not in the order of ORDER")
    for w in WORDS:
        e = EXPRESSIONS[w["n"] - 1]
        hold = w["read"][1] - w["read"][0]
        longest = max(len(line) for line in e["lines"])
        cap = w["frac"] * ASPECT * 0.66 / (0.47 * longest)      # cap height as a share of the picture height
        if hold < 2.5:
            problems.append("%s is readable for only %.1f s" % (e["label"], hold))
        if cap < 0.055:
            problems.append("%s is too small to read on a phone (cap height %.3f)" % (e["label"], cap))
        if not (w["write"][0] <= w["write"][1] <= w["read"][0] < w["read"][1] <= w["leave"][0] < w["leave"][1]):
            problems.append("%s: write, read and leave are out of order" % e["label"])
        if w["read"][1] > MORNING:
            problems.append("%s is still being read at the morning hit" % e["label"])
        if w["anchor"] == "turn":
            for t in np.linspace(w["read"][0], w["read"][1], 5):
                c = camera(float(t))
                (x, y), depth = _project(c, w["at"])
                share = w["width_m"] / frame_width(depth, c["fov"])
                if not (0.50 <= share <= 0.90 and 0.35 <= x <= 0.65 and 0.15 <= y <= 0.88):
                    problems.append("%s at %.1f s: %.0f%% of the width, centre at (%.2f, %.2f)"
                                    % (e["label"], t, share * 100.0, x, y))
    if TOTAL - CARD_FULL < 4.0:
        problems.append("the end card is whole for less than 4 s")
    with open(__file__, encoding="utf-8") as f:
        src = f.read()
    if chr(0x2013) in src or chr(0x2014) in src:
        problems.append("an en dash or em dash is in this file")
    return problems


