# The camera: keyframes in metres and degrees. `camera(t)` below turns them into a pure function of time
# (position, target, field of view, roll, up, focus, aperture), which is what P3D["camera"] takes.
# `up` is the camera's own up vector: it leaves the world's up only in the half loop and in the braid.
# ---------------------------------------------------------------------------------------------------------
CAMERA = []


def _key(t, pos, target, fov, roll=0.0, up=UP, focus=None, aperture=0.0, note=""):
    pos, target = np.asarray(pos, np.float64), np.asarray(target, np.float64)
    CAMERA.append(dict(t=round(float(t), 3), pos=pos, target=target, fov=float(fov), roll=float(roll),
                       up=unit(up), focus=float(np.linalg.norm(target - pos) if focus is None else focus),
                       aperture=float(aperture), note=note))


def _orbit(center, rows, note=""):
    """Keys on an orbit round a centre. rows: (t, azimuth, radius, height, look height, fov, aperture).
    Azimuth rising = the centre on our left (a left turn)."""
    for i, (t, az, r, h, look, fov, ap) in enumerate(rows):
        _key(t, local(center, az, r, h), center + v(0.0, look, 0.0), fov, aperture=ap,
             note=note if i == 0 else "")


